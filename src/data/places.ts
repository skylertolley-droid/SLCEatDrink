export function getPlaceBySlug(slug: string): Place | undefined {
  return places.find((p) => p.slug === slug);
}

export function getNeighborhoods(): string[] {
  return Array.from(new Set(places.map((p) => p.neighborhood))).sort();
}

export function getCuisines(): string[] {
  const set = new Set<string>();
  places.forEach((p) => {
    p.cuisine.forEach((c) => set.add(c));
    p.tags.forEach((t) => {
      // surface a few vibe tags as filterable cuisines/vibes
      if (
        ['brunch', 'cocktails', 'craft beer', 'patio', 'date night'].includes(
          t.toLowerCase()
        )
      ) {
        set.add(t);
      }
    });
  });
  return Array.from(set).sort();
}
